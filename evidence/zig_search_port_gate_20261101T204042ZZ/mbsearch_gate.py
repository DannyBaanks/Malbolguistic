#!/usr/bin/env python3
"""Gate for the Zig port of the level-2 beam search (tools/zig_canonical/mbsearch.zig).

Three tiers, run against binaries built from the sources in this repo:

  corpus        every target: mbsearch must emit a program, `mbc` must print the
                target envelope byte-identically, and every divergence counter
                (peak gaps, stalls, budget exhaustions, '/' executions, delta
                overflows) must stay at zero.
  determinism   the same target and config re-run R times must give one program
                fingerprint.
  differential  with --site-packages holding the malbolge toolkit, the same
                targets are generated by `generate_for_string` with its Random
                replaced by the port's SplitMix64 stream. Same stream on both
                sides, so any difference left is a search difference: programs
                must be byte-identical and evaluation counts equal.

Evidence goes to a fresh dated directory; existing paths are never reused, and
everything recorded is repo-relative (no workstation absolute paths).

  python3 tools/mbsearch_gate.py --mode all --limit 12 --depth 5 \
      --site-packages /path/to/site-packages
"""
from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import pathlib
import shutil
import subprocess
import sys
import tempfile

REPO = pathlib.Path(__file__).resolve().parent.parent
ZIG_SRC = REPO / "tools" / "zig_canonical"
MANIFEST = REPO / "manifest" / "translation_manifest.json"
MBC_STEPS = "5000000000"
DIVERGENCE_KEYS = ("peak_gaps", "stalls", "budget_exhausted", "slash_executed",
                   "delta_overflows")

GOLDEN = 0x9E3779B97F4A7C15
MASK = (1 << 64) - 1


class SharedStream:
    """Mirror of mbsearch.zig Rng: SplitMix64 with rejection below()."""

    def __init__(self, seed: int):
        self.state = (seed + GOLDEN) & MASK
        self.calls = 0

    def _next(self) -> int:
        self.state = (self.state + GOLDEN) & MASK
        z = self.state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
        return z ^ (z >> 31)

    def choice(self, seq):
        n = len(seq)
        limit = MASK - (MASK % n)
        value = self._next()
        while value >= limit:
            value = self._next()
        self.calls += 1
        return seq[value % n]


def sha256_bytes(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def rel(path: pathlib.Path) -> str:
    return path.relative_to(REPO).as_posix()


def build_tools(workdir: pathlib.Path) -> dict:
    pins = {"mbsearch_gate_sha256": sha256_file(REPO / "tools" / "mbsearch_gate.py")}
    for name in ("mbsearch", "mbc"):
        source = ZIG_SRC / f"{name}.zig"
        exe = workdir / name
        subprocess.run(["zig", "build-exe", "-O", "ReleaseFast",
                        f"-femit-bin={exe}", str(source)],
                       check=True, capture_output=True, cwd=REPO)
        pins[f"{name}_source_sha256"] = sha256_file(source)
        pins[f"{name}_binary_sha256"] = sha256_file(exe)
    return pins


def sha256_file(path: pathlib.Path) -> str:
    return sha256_bytes(path.read_bytes())


def pick_entries(limit: int | None, max_bytes: int | None) -> list[dict]:
    chosen = [e for e in json.loads(MANIFEST.read_text())
              if e["malbolge"].get("artifact") and e["malbolge"]["status"] == "PASS"]
    chosen.sort(key=lambda e: e["malbolge"]["chars"])
    if max_bytes is not None:
        chosen = [e for e in chosen
                  if (REPO / e["mirror"]["artifact"]).stat().st_size <= max_bytes]
    return chosen[:limit] if limit is not None else chosen


def run_search(mbsearch: pathlib.Path, target: pathlib.Path, workdir: pathlib.Path,
               tag: str, depth: int, choices: str, seed: int) -> tuple[int, str, dict]:
    program = workdir / f"{tag}.mal"
    stats_file = workdir / f"{tag}.json"
    proc = subprocess.run(
        [str(mbsearch), "--target-file", str(target), "--out", str(program),
         "--stats", str(stats_file), "--depth", str(depth), "--choices", choices,
         "--seed", str(seed)], capture_output=True)
    stats = json.loads(stats_file.read_text()) if proc.returncode == 0 else {}
    return proc.returncode, proc.stderr.decode("utf-8", "replace")[:300], stats


def tier_corpus(mbsearch: pathlib.Path, mbc: pathlib.Path, targets: list[dict],
                depth: int, choices: str, seed: int, workdir: pathlib.Path) -> list[dict]:
    rows = []
    for index, entry in enumerate(targets):
        envelope = REPO / entry["mirror"]["artifact"]
        rc, err, stats = run_search(mbsearch, envelope, workdir, f"corpus_{index}",
                                    depth, choices, seed)
        row = {"source": entry["source"], "envelope": rel(envelope),
               "envelope_bytes": envelope.stat().st_size, "port_rc": rc, "port_stderr": err}
        if rc == 0:
            raw = (workdir / f"corpus_{index}.mal").read_bytes()
            run = subprocess.run([str(mbc), str(workdir / f"corpus_{index}.mal"), MBC_STEPS],
                                 capture_output=True)
            row.update({
                "program_chars": stats["program_chars"],
                "expansion_ratio": stats["expansion_ratio"],
                "evaluations": stats["evaluations"],
                "rng_choices": stats["rng_choices"],
                "in_process_canonical": stats["canonical_ok"],
                "mbc_rc": run.returncode,
                "mbc_output_ok": run.stdout == envelope.read_bytes(),
                "program_sha256": sha256_bytes(raw),
                "committed_artifact": rel(REPO / entry["malbolge"]["artifact"]),
                "byte_equal_committed": raw == (REPO / entry["malbolge"]["artifact"]).read_bytes(),
                **{key: stats[key] for key in DIVERGENCE_KEYS},
            })
        rows.append(row)
        print(json.dumps(row), flush=True)
    return rows


def tier_determinism(mbsearch: pathlib.Path, targets: list[dict], depth: int, choices: str,
                     seed: int, repeats: int, workdir: pathlib.Path) -> list[dict]:
    rows = []
    for index, entry in enumerate(targets[:3]):
        envelope = REPO / entry["mirror"]["artifact"]
        prints = set()
        for rep in range(repeats):
            rc, _, _ = run_search(mbsearch, envelope, workdir, f"det_{index}_{rep}",
                                  depth, choices, seed)
            if rc != 0:
                break
            prints.add(sha256_bytes((workdir / f"det_{index}_{rep}.mal").read_bytes()))
        row = {"envelope": rel(envelope), "repeats": repeats,
               "distinct_fingerprints": len(prints),
               "program_sha256": next(iter(prints)) if len(prints) == 1 else None}
        rows.append(row)
        print(json.dumps(row), flush=True)
    return rows


def tier_differential(mbsearch: pathlib.Path, mbc: pathlib.Path, targets: list[dict],
                      depth: int, choices: str, seed: int, workdir: pathlib.Path,
                      site_packages: str) -> list[dict]:
    sys.path.insert(0, site_packages)
    import malbolge.generator as generator_module
    from malbolge.generator import GenerationConfig, ProgramGenerator

    streams: list[SharedStream] = []
    generator_module.Random = lambda value: streams.append(SharedStream(value)) or streams[-1]
    generator = ProgramGenerator()

    rows = []
    for index, entry in enumerate(targets):
        envelope = REPO / entry["mirror"]["artifact"]
        del streams[:]
        reference = generator.generate_for_string(
            envelope.read_bytes().decode("ascii"),
            config=GenerationConfig(opcode_choices=choices, max_search_depth=depth,
                                    random_seed=seed))
        ref_path = workdir / f"ref_{index}.mal"
        ref_path.write_text(reference.malbolge_program, encoding="ascii", newline="")
        rc, err, stats = run_search(mbsearch, envelope, workdir, f"port_{index}",
                                    depth, choices, seed)
        run = subprocess.run([str(mbc), str(workdir / f"port_{index}.mal"), MBC_STEPS],
                             capture_output=True)
        row = {
            "source": entry["source"], "envelope": rel(envelope),
            "envelope_bytes": envelope.stat().st_size,
            "ref_chars": len(reference.malbolge_program),
            "port_chars": stats.get("program_chars"),
            "byte_equal": rc == 0 and (workdir / f"port_{index}.mal").read_bytes() == ref_path.read_bytes(),
            "ref_evaluations": reference.stats.get("evaluations"),
            "port_evaluations": stats.get("evaluations"),
            "evaluations_equal": stats.get("evaluations") == reference.stats.get("evaluations"),
            "ref_rng_calls": streams[0].calls if streams else None,
            "port_rng_calls": stats.get("rng_choices"),
            "in_process_canonical": stats.get("canonical_ok"),
            "mbc_output_ok": run.stdout == envelope.read_bytes(),
            "port_stderr": err,
            "ref_seconds": round(reference.stats.get("duration_ns", 0) / 1e9, 3),
            "port_seconds": round(stats.get("duration_ns", 0) / 1e9, 4) if stats else None,
        }
        rows.append(row)
        print(json.dumps(row), flush=True)
    return rows


def main() -> int:
    ap = argparse.ArgumentParser(description="mbsearch port gate")
    ap.add_argument("--mode", default="all",
                    choices=["corpus", "determinism", "differential", "all"])
    ap.add_argument("--limit", type=int, default=12)
    ap.add_argument("--max-bytes", type=int, default=None,
                    help="only envelopes of at most this many bytes")
    ap.add_argument("--depth", type=int, default=5)
    ap.add_argument("--choices", default="op*")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--repeats", type=int, default=5)
    ap.add_argument("--differential-limit", type=int, default=None)
    ap.add_argument("--site-packages", default=None,
                    help="site-packages holding the malbolge toolkit (differential tier)")
    ap.add_argument("--out", default=None, help="evidence directory (must not exist)")
    args = ap.parse_args()

    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    outdir = pathlib.Path(args.out) if args.out else (
        REPO / "evidence" / f"zig_search_port_gate_{stamp}Z")
    if outdir.exists():
        raise SystemExit(f"REFUSING to reuse evidence path: {rel(outdir) if outdir.is_relative_to(REPO) else outdir}")
    outdir.mkdir(parents=True)
    workdir = pathlib.Path(tempfile.mkdtemp(prefix="mbsearch_gate_"))

    try:
        pins = build_tools(workdir)
        mbsearch, mbc = workdir / "mbsearch", workdir / "mbc"
        targets = pick_entries(args.limit, args.max_bytes)
        tiers: dict[str, list[dict]] = {}
        with (outdir / "raw.jsonl").open("w", encoding="utf-8") as sink:
            def emit(name: str, rows: list[dict]) -> None:
                tiers[name] = rows
                for row in rows:
                    sink.write(json.dumps({"tier": name, **row}) + "\n")

            if args.mode in ("corpus", "all"):
                emit("corpus", tier_corpus(mbsearch, mbc, targets, args.depth,
                                           args.choices, args.seed, workdir))
            if args.mode in ("determinism", "all"):
                emit("determinism", tier_determinism(mbsearch, targets, args.depth,
                                                     args.choices, args.seed,
                                                     args.repeats, workdir))
            if args.mode in ("differential", "all"):
                if not args.site_packages:
                    raise SystemExit("differential tier needs --site-packages")
                emit("differential", tier_differential(
                    mbsearch, mbc, targets[:args.differential_limit or args.limit],
                    args.depth, args.choices, args.seed, workdir, args.site_packages))
    finally:
        shutil.rmtree(workdir, ignore_errors=True)

    corpus, det, diff = tiers.get("corpus", []), tiers.get("determinism", []), tiers.get("differential", [])
    summary = {
        "config": {"mode": args.mode, "depth": args.depth, "choices": args.choices,
                   "seed": args.seed, "repeats": args.repeats, "targets": len(targets),
                   "manifest": rel(MANIFEST),
                   "manifest_sha256": sha256_file(MANIFEST)},
        "pins": pins,
        "corpus": {
            "n": len(corpus),
            "mbc_output_ok": sum(1 for r in corpus if r.get("mbc_output_ok")),
            "in_process_canonical": sum(1 for r in corpus if r.get("in_process_canonical")),
            "byte_equal_committed": sum(1 for r in corpus if r.get("byte_equal_committed")),
            "divergence_counters": {key: sum(r.get(key, 0) for r in corpus)
                                    for key in DIVERGENCE_KEYS},
            "evaluations_total": sum(r.get("evaluations", 0) for r in corpus),
        },
        "determinism": {"n": len(det),
                        "single_fingerprint": sum(1 for r in det if r["distinct_fingerprints"] == 1)},
        "differential": {
            "n": len(diff),
            "byte_equal": sum(1 for r in diff if r["byte_equal"]),
            "evaluations_equal": sum(1 for r in diff if r["evaluations_equal"]),
            "rng_calls_equal": sum(1 for r in diff if r["ref_rng_calls"] == r["port_rng_calls"]),
            "mbc_output_ok": sum(1 for r in diff if r["mbc_output_ok"]),
            "python_seconds_total": round(sum(r["ref_seconds"] for r in diff), 2),
            "port_seconds_total": round(sum(r["port_seconds"] or 0 for r in diff), 3),
        },
    }
    (outdir / "summary.json").write_text(json.dumps(summary, indent=1) + "\n")
    listed = [p for p in sorted(outdir.iterdir()) if p.name != "SHA256SUMS.txt"]
    (outdir / "SHA256SUMS.txt").write_text(
        "".join(f"{sha256_file(p)}  {p.name}\n" for p in listed))
    print(json.dumps(summary), flush=True)

    broken = (len(corpus) != summary["corpus"]["mbc_output_ok"]
              or len(corpus) != summary["corpus"]["in_process_canonical"]
              or any(r.get(key, 0) for r in corpus for key in DIVERGENCE_KEYS)
              or len(det) != summary["determinism"]["single_fingerprint"]
              or (diff and len(diff) != summary["differential"]["byte_equal"]))
    return 1 if broken else 0


if __name__ == "__main__":
    sys.exit(main())
